import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { validateSkillContent } from "@mastra/core/skills";

const directory = new URL("../skills/zhibi-gaokao-writing-review/", import.meta.url);
const source = (await readFile(new URL("SKILL.md", directory), "utf8")).replaceAll("\r\n", "\n");
const validated = validateSkillContent({ content: source, directoryName: "zhibi-gaokao-writing-review" });
if (!validated.valid) throw new Error(validated.errors.join("\n"));
const references = {};
for (const name of (await readdir(new URL("references/", directory))).sort()) {
  if (!name.endsWith(".md")) throw new Error("Unexpected skill reference format");
  let content = (await readFile(new URL(`references/${name}`, directory), "utf8")).replaceAll("\r\n", "\n");
  // The uploaded sources stay intact in skills/. Shared runtime guidance must
  // not expose the author's private account/library addresses to other students.
  content = content.replace(/https?:\/\/(?:(?:app|www)\.)?notion\.(?:so|site|com)\/[^\s)]+/g, "[原作者个人资料链接，未接入当前账号]")
    .replace(/`[私人资料标识已移除]`/g, "[原作者个人库标识，未接入当前账号]");
  references[name] = content;
}
const manifest = {
  name: validated.metadata.name, description: validated.metadata.description,
  instructions: validated.instructions, references,
  sourceHash: createHash("sha256").update(source).digest("hex")
};
const output = "// Generated by scripts/build-writing-review-skill.mjs; edit skills/zhibi-gaokao-writing-review instead.\nconst data = " + JSON.stringify(manifest, null, 2) + ";\nexport default data;\n";
const target = new URL("../src/lib/ai/skills/writing-review-data.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== output) throw new Error("Writing review bundle is stale");
} else await writeFile(target, output);
console.log(JSON.stringify({ skill: manifest.name, references: Object.keys(references).length, sourceHash: manifest.sourceHash, mode: process.argv.includes("--check") ? "check" : "build" }));
