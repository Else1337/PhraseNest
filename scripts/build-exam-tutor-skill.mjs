import {readFile,writeFile,readdir} from 'node:fs/promises';
import {validateSkillContent} from '@mastra/core/skills';
const directory=new URL('../skills/zhibi-english-exam-tutor/',import.meta.url);
const source=(await readFile(new URL('SKILL.md',directory),'utf8')).replaceAll('\r\n','\n');
const validated=validateSkillContent({content:source,directoryName:'zhibi-english-exam-tutor'});
if(!validated.valid)throw new Error(validated.errors.join('\n'));
const references={};
for(const name of (await readdir(new URL('references/',directory))).sort()){
 if(!name.endsWith('.md'))throw new Error('Unexpected skill reference format');
 references[name]=(await readFile(new URL('references/'+name,directory),'utf8')).replaceAll('\r\n','\n');
}
const manifest={name:validated.metadata.name,description:validated.metadata.description,instructions:validated.instructions,references};
const output='// Generated by scripts/build-exam-tutor-skill.mjs; edit skills/zhibi-english-exam-tutor instead.\nconst data = '+JSON.stringify(manifest,null,2)+';\nexport default data;\n';
const target=new URL('../src/lib/ai/skills/exam-tutor-data.ts',import.meta.url);
if(process.argv.includes('--check')){
 if((await readFile(target,'utf8')).replaceAll('\r\n','\n')!==output)throw new Error('Skill bundle is stale: run node scripts/build-exam-tutor-skill.mjs');
}else await writeFile(target,output);
console.log(JSON.stringify({skill:manifest.name,references:Object.keys(references).length,mode:process.argv.includes('--check')?'check':'build'}));
